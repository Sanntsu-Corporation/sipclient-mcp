package siptest

// Lane A (rfc-sweep-a) pins for the A-HDR area in the siptest request builders.
// Each passes today and must be inverted when its NEW-A finding is fixed.
// These tests reseed the global
// math/rand generator, so they must NOT call t.Parallel (the other tests in this
// package do; Go runs every serial test before any parallel one resumes).

import (
	"math/rand"
	"strings"
	"testing"
	"time"

	"github.com/sanntsu-corporation/sipclient-mcp/internal/sipengine/config"
)

func pinConfig() config.Config {
	return config.Config{
		TargetURI:  "sip:192.168.1.244:5070",
		LocalAddr:  "192.168.1.120:5060",
		FromUser:   "e2e-uac-direct",
		FromDomain: "192.168.1.244",
		ToUser:     "720",
		ToDomain:   "192.168.1.244",
	}
}

// TestRFC3261_NEWA2_BuiltIdentifiersAreIndependentOfTheMathRandSeed covers
// NEW-A-2 (A-HDR-101, RFC 3261 19.3: "When a tag is generated by a UA for
// insertion into a request or response, it MUST be globally unique and
// cryptographically random with at least 32 bits of randomness."
// rfc3261.txt:8876-8878; A-HDR-13 asks the same of Call-IDs,
// rfc3261.txt:2084-2085). Fixed by CF-073: the fork's generators draw from
// crypto/rand, so two builds from the same math/rand seed differ in From tag,
// Call-ID and top Via branch, and the formats are unchanged.
func TestRFC3261_NEWA2_BuiltIdentifiersAreIndependentOfTheMathRandSeed(t *testing.T) {
	// go.mod says go 1.25, where rand.Seed is a no-op unless randseednop=0.
	t.Setenv("GODEBUG", "randseednop=0")
	defer rand.Seed(time.Now().UnixNano()) //nolint:staticcheck // restore a fresh seed for later tests
	rand.Seed(7)                           //nolint:staticcheck // the identical seed is the point of the test
	a := BuildInvite(pinConfig(), "udp", nil)
	rand.Seed(7) //nolint:staticcheck
	b := BuildInvite(pinConfig(), "udp", nil)

	ta, _ := a.From().Params.Get("tag")
	tb, _ := b.From().Params.Get("tag")
	if ta == "" || ta == tb {
		t.Errorf("From tags %q and %q are equal for one seed: the tag is not cryptographically random", ta, tb)
	}
	if a.CallID().Value() == b.CallID().Value() {
		t.Errorf("Call-IDs %q are equal for one seed: not cryptographically random", a.CallID().Value())
	}
	ba, _ := a.Via().Params.Get("branch")
	bb, _ := b.Via().Params.Get("branch")
	if ba == "" || ba == bb {
		t.Errorf("Via branches %q and %q are equal for one seed: not cryptographically random", ba, bb)
	}
	if len(ta) != 8 || !strings.HasPrefix(ba, "z9hG4bK.") || len(ba) != len("z9hG4bK.")+10 {
		t.Errorf("identifier formats changed: tag %q branch %q", ta, ba)
	}
}

// TestRFC3261Pin_NEWA3_RequestURIAndToURIDifferByPort pins NEW-A-3 (A-HDR-02, RFC
// 3261 8.1.1.1: "The initial Request-URI of the message SHOULD be set to the
// value of the URI in the To field." rfc3261.txt:1934-1935). Evidence:
// evidence/corpus-udp/02/excerpt.txt frame 1.
//
// PIN OF A DEVIATION: invert this assertion when NEW-A-3 is fixed.
func TestRFC3261Pin_NEWA3_RequestURIAndToURIDifferByPort(t *testing.T) {
	req := BuildInvite(pinConfig(), "udp", nil)
	if req.Recipient.Port == req.To().Address.Port {
		t.Errorf("Request-URI port %d equals the To URI port: NEW-A-3 is fixed, invert this pin", req.Recipient.Port)
	}
}
