package codec

// dtmf_vectors_test.go — F-M1's fix (D20, P4-W2-01, Phase 4 W2).
//
// testdata/dtmf/'s fixtures carry a reproducibility claim — `make dtmf-vectors`
// regenerates them identically — that had only ever been verified by hand. An
// unverified reproducibility claim is worse than none: it invites a reader to
// trust a regenerated fixture that silently differs.
//
// WHY THIS SHELLS OUT (F-M1's real constraint). scripts/gen-dtmf-vectors is
// `package main` with no importable entry point and no -out flag, and it writes
// to the relative path testdata/dtmf under its own working directory. It cannot
// be called as a library and its output cannot be redirected by argument — so it
// is run as a subprocess with Dir set to t.TempDir(), which is what keeps it from
// overwriting the very fixtures being checked. The generator itself is NOT
// modified: it deliberately carries its own independent sine math so that a
// vector generated by the code under test cannot falsify that code, and
// restructuring it for testability would put an importable seam through that
// independence.
//
// WHY BUILD-THEN-RUN, NOT `go run`. `go run ./scripts/gen-dtmf-vectors` needs
// the module context to resolve the package, but cmd.Dir must be the temp dir
// for the generator's relative testdata/dtmf write to land there — the two
// requirements conflict for a single `go run` invocation. Building the binary
// first (from the module root, cmd.Dir unset) and then running the built binary
// with cmd.Dir set to the temp dir satisfies both: the build resolves the
// module, and the run redirects the write.

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

func TestGeneratedVectorsMatchTheCommittedFixtures(t *testing.T) {
	out := t.TempDir()
	bin := filepath.Join(out, "gen-dtmf-vectors")

	build := exec.Command("go", "build", "-o", bin, "github.com/sanntsu-corporation/sipclient-mcp/scripts/gen-dtmf-vectors")
	if b, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build gen-dtmf-vectors: %v\n%s", err, b)
	}

	run := exec.Command(bin)
	run.Dir = out
	if b, err := run.CombinedOutput(); err != nil {
		t.Fatalf("run gen-dtmf-vectors in %s: %v\n%s", out, err, b)
	}

	committed := filepath.Join("..", "..", "..", "testdata", "dtmf")
	entries, err := os.ReadDir(committed)
	if err != nil {
		t.Fatalf("read committed fixture dir %s: %v", committed, err)
	}
	checked := 0
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || filepath.Ext(name) != ".pcm" {
			continue // skip README.md and anything non-fixture
		}
		want, err := os.ReadFile(filepath.Join(committed, name))
		if err != nil {
			t.Fatalf("read committed fixture %s: %v", name, err)
		}
		got, err := os.ReadFile(filepath.Join(out, "testdata", "dtmf", name))
		if err != nil {
			t.Fatalf("the generator produced no %s (committed fixtures include it): %v", name, err)
		}
		if !bytes.Equal(got, want) {
			t.Fatalf("regenerated %s differs from the committed fixture (%d bytes vs %d). Either the "+
				"generator is not deterministic — which breaks the reproducibility claim in "+
				"testdata/dtmf/ — or the fixture was hand-edited after generation. Run the Makefile's "+
				"dtmf-vectors target and commit the result, or fix the nondeterminism.",
				name, len(got), len(want))
		}
		checked++
	}
	// A zero-fixture pass would be a green test that proves nothing — the exact
	// failure mode this wave's verify-by-mutation rule exists to catch.
	if checked == 0 {
		t.Fatalf("compared 0 fixtures; %s holds no .pcm files, so this test asserts nothing", committed)
	}
}
